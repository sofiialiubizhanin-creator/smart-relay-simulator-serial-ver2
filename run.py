"""One command for the whole project (standard library only).

    python run.py              # set up .venv, install, run the E2E suite 5 times in a row, write reports
    python run.py --runs 1     # a single run
    python run.py demo         # start the simulator (real clock) on ports 5000/5001 for manual use
    python run.py -- -k f1_07  # extra arguments after -- go to pytest
"""
import argparse
import hashlib
import os
import shutil
import subprocess
import sys
import time
import xml.etree.ElementTree as ET
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent
VENV = ROOT / ".venv"
VENV_PY = VENV / ("Scripts/python.exe" if os.name == "nt" else "bin/python")
REPORTS = ROOT / "reports"
RUNS = REPORTS / "runs"


def ensure_venv() -> None:
    if not VENV_PY.exists():
        print("[run] creating .venv")
        subprocess.check_call([sys.executable, "-m", "venv", str(VENV)])
    stamp = VENV / ".installed"
    digest = hashlib.sha256((ROOT / "pyproject.toml").read_bytes()).hexdigest()
    if not stamp.exists() or stamp.read_text() != digest:
        print("[run] installing project and dev dependencies")
        subprocess.check_call([str(VENV_PY), "-m", "pip", "install", "-q", "--disable-pip-version-check",
                               "-e", f"{ROOT}[dev]"])
        stamp.write_text(digest)


def run_suite(runs: int, pytest_args: list[str]) -> int:
    if RUNS.exists():
        shutil.rmtree(RUNS)
    RUNS.mkdir(parents=True)
    rows, failed_runs = [], 0
    for n in range(1, runs + 1):
        html, junit = RUNS / f"e2e-run-{n}.html", RUNS / f"e2e-run-{n}.xml"
        print(f"\n[run] E2E run {n}/{runs}")
        started = time.monotonic()
        code = subprocess.call([str(VENV_PY), "-m", "pytest", "tests/e2e", "-p", "no:cacheprovider",
                                f"--html={html}", "--self-contained-html", f"--junitxml={junit}",
                                *pytest_args], cwd=ROOT)
        duration = time.monotonic() - started
        total = fail = err = skip = 0
        if junit.exists():  # missing when pytest stops before running tests (e.g. a collection error)
            suite = ET.parse(junit).getroot()
            suite = suite if suite.tag == "testsuite" else suite.find("testsuite")
            total, fail, err, skip = (int(suite.get(k, 0)) for k in ("tests", "failures", "errors", "skipped"))
        passed = total - fail - err - skip
        ok = code == 0 and total > 0
        failed_runs += not ok
        rows.append(f"| {n} | {'PASS' if ok else f'FAIL (exit {code})'} | {total} | {passed} | {fail + err} | {skip} | {duration:.1f} s |")
        if html.exists():
            shutil.copy(html, REPORTS / "e2e-report.html")

    summary = REPORTS / "e2e-runs.md"
    summary.write_text(
        "# E2E runs\n\n"
        f"Generated by `python run.py` on {datetime.now().isoformat(timespec='seconds')}, Python {sys.version.split()[0]}.\n"
        f"Result: **{runs - failed_runs}/{runs} runs passed**. Last run report: `reports/e2e-report.html`.\n\n"
        "| Run | Result | Tests | Passed | Failed | Skipped | Duration |\n|---|---|---|---|---|---|---|\n"
        + "\n".join(rows) + "\n", encoding="utf-8")
    print(f"\n[run] {runs - failed_runs}/{runs} runs passed -> {summary.relative_to(ROOT)}, reports/e2e-report.html")
    return 0 if failed_runs == 0 else 1


def demo() -> int:
    print("[run] simulator on serial port 5000, control port 5001 (Ctrl+C to stop)")
    host = r".venv\Scripts\relay-host" if os.name == "nt" else ".venv/bin/relay-host"
    print(f"      in another terminal:  {host} ON   (then: {host} STATUS)")
    try:
        return subprocess.call([str(VENV_PY), "-m", "relay_sim", "--port", "5000", "--control-port", "5001"])
    except KeyboardInterrupt:
        return 0


def main() -> int:
    sys.stdout.reconfigure(line_buffering=True)  # keep [run] lines in order with pytest output
    argv = sys.argv[1:]
    pytest_args = argv[argv.index("--") + 1:] if "--" in argv else []
    argv = argv[:argv.index("--")] if "--" in argv else argv
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("mode", nargs="?", choices=["test", "demo"], default="test")
    p.add_argument("--runs", type=int, default=5, help="consecutive E2E runs (default 5)")
    args = p.parse_args(argv)
    if args.runs < 1:
        p.error("--runs must be at least 1")
    ensure_venv()
    return demo() if args.mode == "demo" else run_suite(args.runs, pytest_args)


if __name__ == "__main__":
    sys.exit(main())
